<?php
// This file contains a small MQTT 3.1.1 client written with plain PHP sockets.
// It implements only what the MVP needs: connect, subscribe, receive messages and ping.

// Strict types make mistakes easier to find while the subscriber runs.
declare(strict_types=1);

// This class talks to a public MQTT broker over a normal TCP connection.
final class MqttClient
{
    // This holds the open TCP socket, or null when there is no active connection.
    private $socket = null;

    // This stores the keep-alive number of seconds agreed with the broker.
    private int $keepAlive = 30;

    // This opens the TCP connection and performs the MQTT CONNECT handshake.
    public function connect(string $host, int $port, string $clientId, int $keepAlive = 30): void
    {
        // Remember the keep-alive value so the subscriber can decide when to ping.
        $this->keepAlive = $keepAlive;

        // Prepare the error variables that stream_socket_client fills in on failure.
        $errorNumber = 0;
        $errorMessage = '';

        // Open a plain TCP connection to the broker with a five-second timeout.
        $socket = @stream_socket_client(
            sprintf('tcp://%s:%d', $host, $port),
            $errorNumber,
            $errorMessage,
            5
        );

        // Stop with a clear message if the broker cannot be reached.
        if ($socket === false) {
            throw new RuntimeException(sprintf('MQTT connection failed: %s (%d)', $errorMessage, $errorNumber));
        }

        // Keep the socket handle so the other methods can read from and write to it.
        $this->socket = $socket;

        // Give every socket read a one-second timeout, so the loop can send pings on time.
        stream_set_timeout($this->socket, 1);

        // Build the CONNECT body: protocol name, level, flags, keep-alive and client ID.
        $payload = $this->encodeString('MQTT') // MQTT protocol name required by version 3.1.1.
            . chr(4)                           // Protocol level 4 means MQTT 3.1.1.
            . chr(0x02)                        // Connect flag 0x02 asks for a clean session.
            . pack('n', $keepAlive)            // Keep-alive interval encoded as a 16-bit number.
            . $this->encodeString($clientId);  // Unique client ID generated by the subscriber.

        // Send the CONNECT packet (header 0x10) and wait for the broker's CONNACK reply.
        $this->writePacket(0x10, $payload);
        $packet = $this->readPacket();

        // A missing reply means the connection attempt failed.
        if ($packet === null) {
            throw new RuntimeException('MQTT broker did not answer the CONNECT request.');
        }

        // CONNACK is type 2, its second body byte is the return code, and 0 means accepted.
        if ($packet['type'] !== 2 || strlen($packet['body']) < 2 || $packet['body'][1] !== "\x00") {
            throw new RuntimeException('MQTT broker rejected the connection.');
        }
    }

    // This subscribes to one topic and requests QoS 0 delivery.
    public function subscribe(string $topic): void
    {
        // The SUBSCRIBE body contains a packet ID, the topic and the requested QoS level.
        $payload = pack('n', 1)             // Packet ID 1 because this client only subscribes once.
            . $this->encodeString($topic)   // The topic filter that the broker should match.
            . chr(0);                       // QoS 0 means "deliver at most once", enough for this MVP.

        // Send the SUBSCRIBE packet (type 8 with the mandatory flags 0x02).
        $this->writePacket(0x82, $payload);

        // Read the broker's SUBACK reply.
        $packet = $this->readPacket();

        // A missing reply means the subscription did not finish in time.
        if ($packet === null) {
            throw new RuntimeException('MQTT broker did not answer the SUBSCRIBE request.');
        }

        // SUBACK is type 9, and a last byte with the high bit set means the broker refused it.
        if ($packet['type'] !== 9 || (ord(substr($packet['body'], -1)) & 0x80) !== 0) {
            throw new RuntimeException('MQTT broker refused the subscription to ' . $topic);
        }
    }

    // This waits up to one second for an incoming message and returns its text.
    public function readMessage(): ?string
    {
        // Read the next packet; null means the one-second read timeout expired.
        $packet = $this->readPacket();

        // Nothing arrived before the timeout, so tell the caller to keep waiting.
        if ($packet === null) {
            return null;
        }

        // Ignore all packet types other than PUBLISH (type 3).
        if ($packet['type'] !== 3) {
            return null;
        }

        // The first two bytes of a PUBLISH body are the topic length.
        $topicLength = unpack('n', substr($packet['body'], 0, 2))[1];

        // Skip the topic bytes to reach the actual JSON sensor message.
        $message = substr($packet['body'], 2 + $topicLength);

        // Return the message payload as a string.
        return $message;
    }

    // This sends a PINGREQ packet so the broker keeps the connection alive.
    public function ping(): void
    {
        // A PINGREQ packet has no body.
        $this->writePacket(0xC0, '');
    }

    // This closes the connection cleanly when the subscriber stops or reconnects.
    public function disconnect(): void
    {
        // Do nothing if no socket is open.
        if ($this->socket === null) {
            return;
        }

        // Try to send DISCONNECT so the broker removes this client immediately.
        try {
            // Header 0xE0 is the MQTT DISCONNECT packet and it has no body.
            $this->writePacket(0xE0, '');
        } catch (Throwable $error) {
            // Ignore write errors because the socket is already being closed.
        }

        // Close the TCP stream to release the connection handle.
        @fclose($this->socket);

        // Forget the socket so it cannot be used again by mistake.
        $this->socket = null;
    }

    // This returns the keep-alive interval so the subscriber knows when to ping.
    public function getKeepAlive(): int
    {
        // Return the number of seconds agreed with the broker.
        return $this->keepAlive;
    }

    // This encodes an MQTT string: a two-byte length followed by the UTF-8 text.
    private function encodeString(string $value): string
    {
        // "n" means a big-endian 16-bit number, which is exactly what MQTT requires.
        return pack('n', strlen($value)) . $value;
    }

    // This writes one complete MQTT packet to the socket.
    private function writePacket(int $header, string $body): void
    {
        // Refuse to write if the object was never connected.
        if ($this->socket === null) {
            throw new RuntimeException('MQTT client is not connected.');
        }

        // The fixed header is the packet type byte plus the encoded body length.
        $packet = chr($header) . $this->encodeLength(strlen($body)) . $body;

        // Write the whole packet to the TCP socket.
        $written = @fwrite($this->socket, $packet);

        // A partial write means the connection is no longer usable.
        if ($written === false || $written < strlen($packet)) {
            throw new RuntimeException('Could not write to the MQTT socket.');
        }
    }

    // This reads one complete MQTT packet, or returns null when a read times out.
    private function readPacket(): ?array
    {
        // Read the first fixed-header byte; null means the read timeout expired.
        $firstByte = $this->readBytes(1);

        // No packet arrived within one second, so let the caller continue its loop.
        if ($firstByte === null) {
            return null;
        }

        // The top four bits of the first byte are the packet type.
        $type = ord($firstByte) >> 4;

        // The remaining length starts at zero and is built from up to four bytes.
        $remainingLength = 0;

        // The multiplier grows by 128 for each extra length byte.
        $multiplier = 1;

        // Initialize the length byte before the loop so the condition always has a value.
        $digit = 0;

        // Keep reading length bytes while the continuation bit (128) is set.
        do {
            // Read one length byte from the socket.
            $lengthByte = $this->readBytes(1);

            // A timeout in the middle of a packet means the connection is broken.
            if ($lengthByte === null) {
                throw new RuntimeException('MQTT connection timed out while reading a packet.');
            }

            // Convert the byte to a number so its bits can be inspected.
            $digit = ord($lengthByte);

            // Add the low seven bits of this byte to the total length.
            $remainingLength += ($digit & 127) * $multiplier;

            // Prepare the multiplier for the next seven-bit group.
            $multiplier *= 128;
        } while (($digit & 128) !== 0);

        // Read the packet body when the packet has one; otherwise use an empty string.
        $body = $remainingLength > 0 ? $this->readBytes($remainingLength) : '';

        // A timeout while reading the body means the packet is incomplete.
        if ($body === null) {
            throw new RuntimeException('MQTT connection timed out while reading a packet body.');
        }

        // Return the packet type and body to the calling method.
        return ['type' => $type, 'body' => $body];
    }

    // This reads exactly the requested number of bytes from the socket.
    private function readBytes(int $length): ?string
    {
        // Refuse to read if the object was never connected.
        if ($this->socket === null) {
            throw new RuntimeException('MQTT client is not connected.');
        }

        // Start with an empty buffer and keep appending until it is complete.
        $data = '';

        // Loop until the requested number of bytes has arrived.
        while (strlen($data) < $length) {
            // Read only the number of bytes that are still missing.
            $chunk = @fread($this->socket, $length - strlen($data));

            // Handle a read timeout or a socket that the broker closed.
            if ($chunk === false || $chunk === '') {
                // Ask PHP whether this was a timeout or a real disconnect.
                $meta = stream_get_meta_data($this->socket);

                // A timeout is normal: return null so the caller can send a ping and retry.
                if ($meta['timed_out']) {
                    return null;
                }

                // Anything else means the broker or network closed the connection.
                throw new RuntimeException('MQTT connection was closed by the broker.');
            }

            // Append the newly received bytes to the buffer.
            $data .= $chunk;
        }

        // Return exactly the requested bytes.
        return $data;
    }

    // This encodes an MQTT "remaining length" into one to four bytes.
    private function encodeLength(int $length): string
    {
        // Start with an empty result string.
        $encoded = '';

        // Encode seven bits per byte until the whole length has been consumed.
        do {
            // Take the lowest seven bits of the remaining length.
            $digit = $length % 128;

            // Shift the remaining value down by seven bits.
            $length = intdiv($length, 128);

            // Set the continuation bit when another length byte is still needed.
            if ($length > 0) {
                $digit |= 128;
            }

            // Append this length byte to the result.
            $encoded .= chr($digit);
        } while ($length > 0);

        // Return the encoded length bytes.
        return $encoded;
    }
}
